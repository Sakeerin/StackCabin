use stackcabin_core::models::*;
use ts_rs::TS;
fn main() -> anyhow::Result<()> {
    let declarations = [
        Preset::decl(),
        RuntimeSelection::decl(),
        ProcessSpec::decl(),
        DatabaseEngine::decl(),
        DatabaseBinding::decl(),
        ProjectSpec::decl(),
        Project::decl(),
        ProcessState::decl(),
        ProcessInfo::decl(),
        ProjectStatus::decl(),
        RuntimeArtifact::decl(),
        RuntimeInfo::decl(),
        Settings::decl(),
        Diagnostic::decl(),
        BackupInfo::decl(),
        ServiceInfo::decl(),
        Snapshot::decl(),
        AppEvent::decl(),
    ];
    let text = format!(
        "// Generated by npm run types. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|d| format!("export {d}"))
            .collect::<Vec<_>>()
            .join("\n\n")
    );
    std::fs::write(
        concat!(env!("CARGO_MANIFEST_DIR"), "/../../src/lib/types.ts"),
        text,
    )?;
    Ok(())
}
